import { useEffect, useMemo, useState } from 'react'
import { API_BASE, WS_BASE } from '../lib/api'















import Township3D from '../components/Township3D'
import LiveScenarioBar from '../components/LiveScenarioBar'































function DigitalTwin({
  targetSensor,
  clearTargetSensor,
  initialLiveWT04,
  onLiveWT04Change,
}) {















  const [, setSelectedZone] = useState('C')















  const [selectedSensorID, setSelectedSensorID] = useState(null)






























  // =====================================================















  // LIVE WT-04 STATE















  // =====================================================















  const [liveWT04, setLiveWT04] = useState(
    initialLiveWT04 ?? {
      value: 3.2,
      status: 'Normal',
      connected: false,
    }
  )



  const [liveWT03, setLiveWT03] = useState({
    value: 124,
    status: 'Normal',
    connected: false,
  })


  const [liveEN12, setLiveEN12] = useState({

    value: 428,

    status: 'Normal',

    connected: false,

  })



  const [liveTR08, setLiveTR08] = useState({
    value: 64,
    status: 'Normal',
    connected: false,
  })

  // Keep the parent Overview synchronized with the exact WT-04 state
  // used by the Digital Twin.
  useEffect(() => {
    if (onLiveWT04Change) {
      onLiveWT04Change(liveWT04)
    }
  }, [liveWT04, onLiveWT04Change])



  const [scenarioAnomaly, setScenarioAnomaly] = useState(null)















  const [, setSimulationRunning] =















    useState(false)















  const [anomaly, setAnomaly] = useState(null)







  // =====================================================



  // SCENARIO SIMULATOR



  // =====================================================



  



  



  



  































  // =====================================================















  // ENTERPRISE IOT DATA PIPELINE















  // =====================================================































  const [, setIotPipeline] = useState({















    status: 'STANDBY',















    mqtt_ingestion: 'READY',















    event_bus: 'READY',















    devices_total: 4,















    devices_online: 4,















    device_health_percent: 100,















    events_processed: 0,















    ingestion_rate_msg_s: 0,















    average_pipeline_latency_ms: 0,















  })































  const [, setIotEvents] = useState([])















  















  // =====================================================















  // SENSOR DATA















  // =====================================================















  const sensors = useMemo(















    () => ({















      'EN-12': {















        id: 'EN-12',















        name: 'Energy Monitor',















        zone: 'Zone A',















        zoneKey: 'A',















        type: 'Electrical Grid',















        value: `${liveEN12.value} kW`,















        status: liveEN12.status,















        updated: '2 sec ago',















      },















      'TR-08': {















        id: 'TR-08',















        name: 'Traffic Sensor',















        zone: 'Zone B',















        zoneKey: 'B',















        type: 'Mobility Network',















        value: `${liveTR08.value} veh/min`,















        status: liveTR08.status,















        updated: '1 sec ago',















      },















      'WT-03': {















        id: 'WT-03',















        name: 'Water Flow Sensor',















        zone: 'Zone C',















        zoneKey: 'C',















        type: 'Water Network',















        value: `${liveWT03.value} L/min`,















        status: liveWT03.status,















        updated: liveWT03.connected ? 'Live' : 'Gateway Offline',















      },















      'WT-04': {















        id: 'WT-04',















        name: 'Water Pressure Sensor',















        zone: 'Zone C',















        zoneKey: 'C',















        type: 'Water Network',















        value: `${liveWT04.value} bar`,















        status: liveWT04.status,















        updated: liveWT04.connected















          ? 'Live'















          : 'Gateway Offline',















      },















    }),















    [liveWT03, liveWT04, liveEN12, liveTR08]















  )















  















  const selectedSensor = selectedSensorID















    ? sensors[selectedSensorID]















    : null















  // =====================================================















  // IOT PIPELINE INITIAL SNAPSHOT















  // =====================================================































  useEffect(() => {















    const loadPipeline = async () => {















      try {















        const [pipelineResponse, eventsResponse] = await Promise.all([















          fetch(`${API_BASE}/api/iot/pipeline`),















          fetch(`${API_BASE}/api/iot/events?limit=12`),















        ])































        if (pipelineResponse.ok) {















          setIotPipeline(await pipelineResponse.json())















        }































        if (eventsResponse.ok) {















          const payload = await eventsResponse.json()















          setIotEvents([...(payload.events || [])].reverse())















        }















      } catch (error) {















        console.error('Unable to load NEXORA IoT pipeline:', error)















      }















    }































    loadPipeline()















  }, [])































  // =====================================================















  // NEXORA REAL-TIME DATA GATEWAY















  // =====================================================































  useEffect(() => {















    let socket = null















    let reconnectTimer = null















    let intentionallyClosed = false















    const connectGateway = () => {















      socket = new WebSocket(















        WS_BASE + '/ws'















      )















      socket.onopen = () => {















        console.log(















          'NEXORA Real-Time Gateway connected'















        )















        setLiveWT04((current) => ({















          ...current,















          connected: true,















        }))

        setLiveWT03((current) => ({ ...current, connected: true }))
        setLiveEN12((current) => ({ ...current, connected: true }))
        setLiveTR08((current) => ({ ...current, connected: true }))















        socket.send('NEXORA_CLIENT_CONNECTED')















      }















      socket.onmessage = (event) => {















        try {















          const message = JSON.parse(event.data)















          console.log(















            'NEXORA LIVE EVENT:',















            message















          )















          // ---------------------------------------------















          // CONNECTION MESSAGE















          // ---------------------------------------------















          if (message.event === 'CONNECTED') {















            setLiveWT04((current) => ({















              ...current,















              connected: true,















            }))















            return















          }















          // ---------------------------------------------















          // ENTERPRISE IOT PIPELINE















          // ---------------------------------------------































          if (message.event === 'IOT_PIPELINE_STATUS') {















            setIotPipeline(message.data)















            return















          }































          if (message.event === 'IOT_PIPELINE_EVENT') {
            const pipelineEvent = message.data

            setIotEvents((current) =>
              [pipelineEvent, ...current].slice(0, 12)
            )

            const formattedStatus =
              pipelineEvent?.status === 'CRITICAL'
                ? 'Critical'
                : pipelineEvent?.status === 'WARNING'
                  ? 'Warning'
                  : 'Normal'

            // Feed the virtual MQTT telemetry into the same live state used
            // by the 2D map, sensor details and the 3D Digital Twin.
            if (pipelineEvent?.device_id === 'WT-03') {
              setLiveWT03({
                value: pipelineEvent.value,
                status: formattedStatus,
                connected: true,
              })
            }

            if (pipelineEvent?.device_id === 'EN-12') {
              setLiveEN12({
                value: pipelineEvent.value,
                status: formattedStatus,
                connected: true,
              })
            }

            if (pipelineEvent?.device_id === 'TR-08') {
              setLiveTR08({
                value: pipelineEvent.value,
                status: formattedStatus,
                connected: true,
              })
            }

            // WT-04 is scenario-sensitive. The backend reading already reflects
            // the current scenario state, so pipeline telemetry can safely keep
            // its displayed pressure synchronized without inventing new values.
            if (pipelineEvent?.device_id === 'WT-04') {
              setLiveWT04((current) => ({
                ...current,
                value: pipelineEvent.value,
                status: formattedStatus,
                connected: true,
              }))
            }

            return
          }

































          // ---------------------------------------------















          // SENSOR UPDATE / RESET















          // ---------------------------------------------















          if (















            message.event === 'SENSOR_UPDATE' ||















            message.event === 'SYSTEM_RESET'















          ) {















            const sensor = message.data















            if (sensor?.sensor_id !== 'WT-04') {















              return















            }















            const formattedStatus =















              sensor.status === 'CRITICAL'















                ? 'Critical'















                : sensor.status === 'WARNING'















                  ? 'Warning'















                  : 'Normal'















            setLiveWT04({















              value: sensor.value,















              status: formattedStatus,















              connected: true,















            })















            if (















              message.event === 'SYSTEM_RESET'















            ) {















              setAnomaly(null)















              setSimulationRunning(false)















            }















            return















          }















          // ---------------------------------------------

          // MULTI-SCENARIO SENSOR UPDATE

          // ---------------------------------------------



          if (message.event === 'SCENARIO_SENSOR_UPDATE') {

            const sensor = message.data

            const formattedStatus =

              sensor.status === 'CRITICAL'

                ? 'Critical'

                : sensor.status === 'WARNING'

                  ? 'Warning'

                  : 'Normal'



            if (sensor.sensor_id === 'EN-12') {

              setLiveEN12({

                value: sensor.value,

                status: formattedStatus,

                connected: true,

              })

            }



            if (sensor.sensor_id === 'TR-08') {

              setLiveTR08({

                value: sensor.value,

                status: formattedStatus,

                connected: true,

              })

            }



            if (sensor.scenario === 'RESET') {

              setScenarioAnomaly(null)

              setSimulationRunning(false)

            }

            return

          }



          if (message.event === 'SCENARIO_ANOMALY') {

            const sensor = message.data

            setScenarioAnomaly(sensor)

            setSimulationRunning(false)



            if (sensor.sensor_id === 'EN-12') {

              setLiveEN12({ value: sensor.value, status: 'Critical', connected: true })

              setSelectedZone('A')

              setSelectedSensorID('EN-12')

            }



            if (sensor.sensor_id === 'TR-08') {

              setLiveTR08({ value: sensor.value, status: 'Critical', connected: true })

              setSelectedZone('B')

              setSelectedSensorID('TR-08')

            }

            return

          }



          // ---------------------------------------------















          // ANOMALY EVENT















          // ---------------------------------------------















          if (















            message.event === 'ANOMALY_DETECTED'















          ) {















            setAnomaly(message.data)















            setSimulationRunning(false)















            setLiveWT04({















              value: message.data.value,















              status: 'Critical',















              connected: true,















            })















            setSelectedZone('C')















            setSelectedSensorID('WT-04')















          }















        } catch (error) {















          console.error(















            'Invalid NEXORA Gateway event:',















            error















          )















        }















      }















      socket.onerror = (error) => {















        console.error(















          'NEXORA Gateway connection error:',















          error















        )















      }















      socket.onclose = () => {















        console.log(















          'NEXORA Gateway disconnected'















        )















        setLiveWT04((current) => ({















          ...current,















          connected: false,















        }))















        if (!intentionallyClosed) {















          reconnectTimer = setTimeout(() => {















            connectGateway()















          }, 2000)















        }















      }















    }















    connectGateway()















    return () => {















      intentionallyClosed = true















      if (reconnectTimer) {















        clearTimeout(reconnectTimer)















      }















      if (socket) {















        socket.close()















      }















    }















  }, [])















  // =====================================================















  // AUTO OPEN SENSOR FROM OTHER MODULES















  // =====================================================















  useEffect(() => {















    if (!targetSensor) return















    const sensor = sensors[targetSensor]















    if (!sensor) return















    setSelectedZone(sensor.zoneKey)















    setSelectedSensorID(sensor.id)















    if (clearTargetSensor) {















      clearTargetSensor()















    }















  }, [















    targetSensor,















    clearTargetSensor,















    sensors,















  ])















  // =====================================================















  // OPEN ZONE















  // =====================================================















  















  // =====================================================















  // OPEN SENSOR















  // =====================================================















  const openSensor = (sensorID) => {















    const sensor = sensors[sensorID]















    if (!sensor) return















    setSelectedZone(sensor.zoneKey)















    setSelectedSensorID(sensor.id)















  }















  // =====================================================















  // RUN SCENARIO SIMULATION















  // =====================================================















  



  



  



  // =====================================================















  // RESET WATER SIMULATION















  // =====================================================















  















  // =====================================================















  // IOT PIPELINE CONTROLS















  // =====================================================































  































  































  // =====================================================















  // MARKER STATUS















  // =====================================================















  















  return (















    <section className="digital-twin-page">















      {/* =================================================















          PAGE HEADER















      ================================================= */}















      <div className="dt-heading dt-heading-clean">

        <div className="dt-heading-copy">

          <div className="dt-title-row">

            <div>

              <p className="section-label">DIGITAL TWIN</p>

              <h1>Township Digital Twin</h1>

            </div>



            {/* gateway badge removed for the water-only demo */}

          </div>



          <p className="dt-description">

            Real-time spatial intelligence and infrastructure monitoring.

          </p>




        </div>

      </div>






      {/* Live township scenarios — drive the /api/v2 engine (work orders, resident alerts, 3D water layer) */}
      <LiveScenarioBar />

      {/* =================================================















          MAIN DIGITAL TWIN















      ================================================= */}















      <div className="dt-layout">















        {/* ===============================================















            MAP















        =============================================== */}






















          <Township3D







            liveWT03={liveWT03}
            liveWT04={liveWT04}

            liveEN12={liveEN12}

            liveTR08={liveTR08}

            onSensorSelect={openSensor}







          />






















{/* ===============================================















            RIGHT PANEL















        =============================================== */}















        <aside className="zone-details">















          {selectedSensor ? (















            <div className="sensor-details">















              <button















                type="button"















                className="sensor-back"















                onClick={() =>















                  setSelectedSensorID(null)















                }















              >















                ← BACK TO ZONE















              </button>















              <p className="section-label">















                SENSOR NODE















              </p>















              <div className="sensor-detail-heading">















                <div>















                  <h2>















                    {selectedSensor.id}















                  </h2>















                  <span>















                    {selectedSensor.name}















                  </span>















                </div>















                <span















                  className={















                    selectedSensor.status ===















                    'Critical'















                      ? 'sensor-health critical'















                      : selectedSensor.status ===















                          'Warning'















                        ? 'sensor-health warning'















                        : 'sensor-health'















                  }















                >















                  ● {selectedSensor.status}















                </span>















              </div>















              <div className="sensor-reading">















                <span>















                  LIVE READING















                </span>















                <strong>















                  {selectedSensor.value}















                </strong>















                <small>















                  Updated {selectedSensor.updated}















                </small>















              </div>















              <div className="sensor-meta">















                <div>















                  <span>LOCATION</span>















                  <strong>















                    {selectedSensor.zone}















                  </strong>















                </div>















                <div>















                  <span>NETWORK</span>















                  <strong>















                    {selectedSensor.type}















                  </strong>















                </div>















                <div>















                  <span>NODE ID</span>















                  <strong>















                    {selectedSensor.id}















                  </strong>















                </div>















              </div>















              {/* =========================================















                  LIVE GATEWAY INFORMATION















              ========================================= */}















              {selectedSensor.id === 'WT-04' && (















                <div className="dt-gateway-card">















                  <div>















                    <span>















                      REAL-TIME GATEWAY















                    </span>















                    <strong















                      className={















                        liveWT04.connected















                          ? 'gateway-text-online'















                          : 'gateway-text-offline'















                      }















                    >















                      ●{' '}















                      {liveWT04.connected















                        ? 'CONNECTED'















                        : 'OFFLINE'}















                    </strong>















                  </div>















                  <p>















                    Live telemetry received through















                    NEXORA FastAPI WebSocket Gateway.















                  </p>















                </div>















              )}















              {selectedSensor.id !== 'WT-04' &&

                scenarioAnomaly?.sensor_id === selectedSensor.id && (

                  <div className="dt-anomaly-card">

                    <div className="dt-anomaly-top">

                      <div>

                        <span>NEXORA SCENARIO INTELLIGENCE</span>

                        <h3>{scenarioAnomaly.type}</h3>

                      </div>

                      <strong>{scenarioAnomaly.severity}</strong>

                    </div>



                    <div className="dt-anomaly-grid">

                      <div>

                        <span>SENSOR</span>

                        <strong>{scenarioAnomaly.sensor_id}</strong>

                      </div>

                      <div>

                        <span>SCENARIO</span>

                        <strong>

                          {scenarioAnomaly.scenario === 'TRAFFIC_SURGE'

                            ? 'TRAFFIC SURGE'

                            : 'POWER OVERLOAD'}

                        </strong>

                      </div>

                    </div>



                    <div className="dt-recommendation">

                      <span>OPERATIONAL IMPACT</span>

                      <p>{scenarioAnomaly.impact}</p>

                    </div>



                    <div className="dt-recommendation">

                      <span>RECOMMENDED ACTION</span>

                      <p>{scenarioAnomaly.recommended_action}</p>

                    </div>

                  </div>

                )}



              {/* =========================================















                  PREDICTIVE ANOMALY















              ========================================= */}















              {selectedSensor.id === 'WT-04' &&















                anomaly && (















                  <div className="dt-anomaly-card">















                    <div className="dt-anomaly-top">















                      <div>















                        <span>















                          NEXORA INTELLIGENCE















                        </span>















                        <h3>















                          Predictive Risk Detected















                        </h3>















                      </div>















                      <strong>















                        CRITICAL















                      </strong>















                    </div>















                    <div className="dt-risk-score">















                      <span>















                        FAILURE RISK















                      </span>















                      <strong>















                        {anomaly.failure_risk}%















                      </strong>















                    </div>















                    <div className="dt-anomaly-grid">















                      <div>















                        <span>















                          SENSOR















                        </span>















                        <strong>















                          {anomaly.sensor_id}















                        </strong>















                      </div>















                      <div>















                        <span>















                          FAILURE WINDOW















                        </span>















                        <strong>















                          {















                            anomaly.predicted_failure_window















                          }















                        </strong>















                      </div>















                    </div>















                    <div className="dt-recommendation">















                      <span>















                        RECOMMENDED ACTION















                      </span>















                      <p>















                        {















                          anomaly.recommended_action















                        }















                      </p>















                    </div>















                  </div>















                )}















            </div>















          ) : (
            <div className="zone-hint">
              <p className="section-label">SENSORS</p>
              <p>Click a sensor in the 3D model to see its live reading.</p>
            </div>
          )}















        </aside>















      </div>






























































    </section>















  )















}















export default DigitalTwin
